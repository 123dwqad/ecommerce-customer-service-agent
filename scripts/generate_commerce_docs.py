def header(title, docno, custom_meta=None):
    s = [Paragraph(title, s_red), Paragraph(docno, s_no), Spacer(1, 6), RL(), Spacer(1, 12),
         T(meta_rows(custom_meta), META_COLS), Spacer(1, 6), Paragraph(DOC_TIP, s_nt), Spacer(1, 6)]
    return s


def footer(canv, doc):
    canv.saveState()
    canv.setFont(F, 8)
    canv.setFillColor(colors.grey)
    canv.drawString(2.2 * cm, 1.2 * cm, FOOTER_TEXT)
    canv.drawRightString(A4[0] - 2.2 * cm, 1.2 * cm, "第 %d 页" % canv.getPageNumber())
    canv.restoreState()


# ======================== 流程图 ========================
class FC(Flowable):
    def __init__(self, steps, w=16 * cm):
        Flowable.__init__(self)
        self.steps = steps
        self.width = w
        self.bh = 1.1 * cm
        self.gp = 0.5 * cm
        self.height = len(steps) * (self.bh + self.gp) + self.gp

    def draw(self):
        c = self.canv
        x, w = 0, self.width
        y = self.height - self.bh
        for i, (lb, bt) in enumerate(self.steps):
            if bt in ('start', 'end'):
                c.setFillColor(colors.HexColor('#2e75b6'))
                c.roundRect(x, y, w, self.bh, 6, fill=1, stroke=0)
                c.setFillColor(colors.white)
                c.setFont(F, 9)
                c.drawCentredString(x + w / 2, y + self.bh / 2 - 3, lb)
            elif bt == 'decision':
                c.setFillColor(colors.HexColor('#ffd966'))
                cx, cy = x + w / 2, y + self.bh / 2
                p = c.beginPath()
                p.moveTo(cx, y + self.bh)
                p.lineTo(x + w, cy)
                p.lineTo(cx, y)
                p.lineTo(x, cy)
                p.close()
                c.drawPath(p, fill=1, stroke=0)
                c.setFillColor(colors.black)
                c.setFont(F, 8)
                c.drawCentredString(cx, cy - 3, lb)
            else:
                c.setFillColor(colors.HexColor('#deebf7'))
                c.setStrokeColor(colors.HexColor('#2e75b6'))
                c.setLineWidth(1)
                c.rect(x, y, w, self.bh, fill=1, stroke=1)
                c.setFillColor(colors.black)
                c.setFont(F, 8.5)
                c.drawCentredString(x + w / 2, y + self.bh / 2 - 3, lb)
            if i < len(self.steps) - 1:
                ay = y - self.gp
                c.setStrokeColor(colors.HexColor('#404040'))
                c.setLineWidth(1.2)
                c.line(x + w / 2, y, x + w / 2, ay)
                c.line(x + w / 2, ay, x + w / 2 - 3, ay + 4)
                c.line(x + w / 2, ay, x + w / 2 + 3, ay + 4)
            y -= (self.bh + self.gp)


# ======================== 表格 / 红线 ========================
def T(data, cw, bg='#1f4e79'):
    hdr = [Paragraph(str(c), s_th) for c in data[0]]
    rows = [[Paragraph(str(c), s_tc) if i > 0 else Paragraph(str(c), s_tcc)
             for i, c in enumerate(r)] for r in data[1:]]
    t = Table([hdr] + rows, colWidths=cw, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor(bg)),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#bfbfbf')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f2f7fc')]),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 3), ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
    ]))
    return t


def RL():
    return Table([['']], colWidths=[16 * cm], rowHeights=[2],
                 style=TableStyle([('LINEABOVE', (0, 0), (-1, 0), 2, colors.HexColor('#C00000'))]))


def H1(t):
    return Paragraph(t, s_h1)


def H2(t):
    return Paragraph(t, s_h2)


def H3(t):
    return Paragraph(t, s_h3)


def P(t):
    return Paragraph(t, s_ni)


def B(items):
    return [Paragraph('• ' + it, s_ni) for it in items]


def build(fn, flowables, pagebreak_every=False):
    def _flat(items):
        out = []
        for f in items:
            if isinstance(f, (list, tuple)):
                out.extend(_flat(f))
            else:
                out.append(f)
        return out

    flowables = _flat(flowables)
    d = SimpleDocTemplate(os.path.join(OUT, fn), pagesize=A4, leftMargin=2.2 * cm,
                          rightMargin=2.2 * cm, topMargin=2.5 * cm, bottomMargin=2 * cm)
    from reportlab.platypus import PageBreak
    if pagebreak_every:
        out = []
        for i, f in enumerate(flowables):
            out.append(f)
            if i < len(flowables) - 1 and i % pagebreak_every == pagebreak_every - 1:
                out.append(PageBreak())
        flowables = out
    d.build(flowables, onFirstPage=footer, onLaterPages=footer)
    print("generated:", os.path.join(OUT, fn))


